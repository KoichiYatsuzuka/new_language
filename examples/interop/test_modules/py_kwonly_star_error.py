"""py_kwonly_star_error.py — 名前つき `*args` とキーワード専用引数の併用（変換器が明示エラーにする形）。

Arrow の可変長パラメータは**必ず末尾**でなければならず、`Param` に「位置渡し禁止」の
フラグが無い。そのため `[a, b, ...]` と平坦化するしかなく、`b` が位置引数のスロットを
占めてしまう:

    f(1, b=9)        -> (1, 0, 9)   たまたま合う（位置引数が余らない）
    f(1, 2, 3, b=9)  -> TypeError: argument 'b' given twice

⚠ **呼び方によって通ったり壊れたりする**のが厄介なので、変換時に止める。
   bare `*`（名前なし）は対象外で、`py_kwonly.py` の 6 形は通り続ける。
"""


def f(a, *rest, b):
    return (a, len(rest), b)
