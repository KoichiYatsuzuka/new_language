// codegen.rs — Handle-based Rust source generator for tl module functions.
//
// All values crossing the module boundary are `i64` handles into a thread-local
// value arena owned by the interpreter (see interpreter/native_api.rs).
//
// The generated code receives a `TlCallbacks` struct pointer via `tl_init(cb)`
// at load time. Every value operation (arithmetic, attr access, function calls,
// iteration) routes through these callbacks, so ALL types are supported.
//
// Eligibility: a function is compiled natively when its body contains none of:
//   - yield / yield from (generator functions)
//   - inner fn / gen definitions (closures)
//   - try / except / raise (exception handling)
//   - block_return / loop_yield (block expressions)
//   - keyword arguments in any call site
//   - static mut declarations
//   - import statements

use std::collections::{HashMap, HashSet};

use crate::ast::{BinOp, CallArg, Expr, MatchPattern, Param, Stmt, UnaryOp};

// ── Public types ─────────────────────────────────────────────────────────────

/// ネイティブにエクスポートされた関数のメタデータ。
/// 関数名とパラメータ数を保持し、DLL呼び出し時に使用される。
#[derive(Debug, Clone)]
pub struct FnExport {
    pub name: String,
    pub n_params: usize,
}

